@prefix-cls: ~'@{namespace}-setting';

.@{prefix-cls} {
  border-radius: var(--radius-sm) 0 0 var(--radius-sm);
}
.palette-note { color: var(--text-secondary); font-size: 13px; line-height: 1.6; margin: 20px 4px; }
